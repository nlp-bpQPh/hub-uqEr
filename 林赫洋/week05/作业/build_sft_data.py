# 问法变体：同一个问题换一种问法，让模型不要只认一种句式
AUG_PREFIXES = ["", "请解释一下：", "简单说说："]


def augment(pairs):
    """给以「？」结尾的问题加两种问法；日常寒暄保持原样。

    每条都带 pair_id：同一个问题的几种问法属于同一组，
    后面切训练/验证集时整组一起走，避免验证集里出现训练集见过的答案。
    """
    out = []
    for idx, (q, a) in enumerate(pairs):
        keep = q.endswith("？") and len(q) >= 6
        prefixes = AUG_PREFIXES if keep else [""]
        for p in prefixes:
            out.append({"pair_id": idx, "question": p + q, "answer": a})
    return out


def main():
    rows = augment(PAIRS)
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    q_len = sum(len(r["question"]) for r in rows) / len(rows)
    a_len = sum(len(r["answer"]) for r in rows) / len(rows)
    print(f"原始问答对 : {len(PAIRS)} 条")
    print(f"问法扩充后 : {len(rows)} 条")
    print(f"问题平均长度: {q_len:.1f} 字")
    print(f"回答平均长度: {a_len:.1f} 字")
    print(f"已写入     : {OUT_PATH}")


if __name__ == "__main__":
    main()
